export function getLocale(language) {
  const candidate = language ?? (typeof navigator !== 'undefined' ? navigator.language : '');
  return ENGLISH_LOCALE.test(String(candidate || '')) ? 'en' : 'zh';
}

export function isEnglish(language) {
  return getLocale(language) === 'en';
}

export function t(key, language, values = {}) {
  const value = COPY[getLocale(language)]?.[key] ?? COPY.zh[key] ?? key;
  return String(value).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function figureLabel(name, language) {
  return isEnglish(language) ? FIGURE_LATIN_NAMES[name] || name : name;
}

export function membershipTierLabel(tier, language) {
  return t(tier === 'advanced' ? 'advancedMembership' : 'basicMembership', language);
}

export function membershipIntervalLabel(interval, language) {
  return t(interval === 'year' ? 'yearly' : 'monthly', language);
}

export function brandName(language) {
  return t('brand', language);
}
